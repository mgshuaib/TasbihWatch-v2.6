//  GestureCompat.swift
//  سبحة — توافق الإيماءة مع إصدارات watchOS
//
//  تستخدمها الشاشة والودجت. تسمح لك بجعل هدف النشر watchOS 10
//  مع بقاء الإيماءة تعمل على watchOS 11 وما بعده.
//
//  ⚠️ درس مهم (سجل الإصلاحات) — سبب فشل أول ترجمة حقيقية على سيرفر أبل:
//     كان هنا إيماءة ثانية تسمى `.gestureButton`، وهي **غير موجودة** في واجهة أبل:
//     نوع `HandGestureShortcut` يحوي قيمة واحدة فقط: `.primaryAction`.
//     والملف (وهو مشترك بين التطبيق والودجت) لم يُترجم على هدفين × معالجين = **٤ أخطاء**.
//     الحقيقة: **إيماءة يد واحدة لكل شاشة** — لا توجد إيماءة ثانوية للنقرة المزدوجة.
//

import SwiftUI

extension View {

    /// الإجراء الرئيسي: «الضغط مرة واحدة (نقرتان متلاحقتان) بالإصبعين» يزيد الذكر.
    ///
    /// `enabled: false` تُعطّل الإيماءة — نستخدمها عندما تكون القائمة المنسدلة مفتوحة
    /// حتى لا يعدّ المستخدم أذكارًا وهو يتنقّل في الإعدادات.
    ///
    /// ملاحظة: أبل تشترط أن يكون الهدف زرًّا (Button) أو مفتاحًا (Toggle)،
    /// وزرًّا **واحدًا فقط** في الشاشة يحمل الإيماءة.
    @ViewBuilder
    func primaryTapShortcut(enabled: Bool = true) -> some View {
        if #available(watchOS 11.0, *) {
            self.handGestureShortcut(.primaryAction, isEnabled: enabled)
        } else {
            self
        }
    }

    /// ⚠️ **لا تضيف هذه الدالة أي إيماءة** — وهي موثّقة بصدق هنا عن قصد:
    ///
    /// أبل تتيح إيماءة يد **واحدة** لكل شاشة: `.primaryAction` (وهي عندنا لتسجيل الذكر في `primaryTapShortcut`).
    /// أما الإيماءة الثانية التي كنّا نحاول ربطها بزر تبديل العرض (`.gestureButton`) فغير موجودة أصلًا
    /// في SwiftUI/WatchKit، واستخدامها كان يُفشل الترجمة.
    ///
    /// لذلك: زر تبديل طريقة العرض **يعمل باللمس العادي**، ودور النقرة المزدوجة يبقى محفوظًا
    /// للوظيفة الأهم في التطبيق: تسجيل الذكر. أبقينا الدالة في مكانها (وليس حذفها)
    /// حتى تبقى نقطة واحدة سهلة عند إضافة أبل لإيماءات جديدة مستقبلًا.
    @ViewBuilder
    func secondaryTapShortcut(enabled: Bool = true) -> some View {
        // لا شيء مقصود: نُعيد العرض كما هو. (لا `handGestureShortcut` هنا — غير متاح لأكثر من إجراء واحد)
        self
    }
}
