    body = '\n'.join(f'  "{lbl}": "{full}",' for lbl, full in entries)
    new_sim = new_sim[:k3] + 'const FULL = {\n' + body + new_sim[j3:]

    # ── تقرير ──
    print('المجموعات الكتابية الأربع:')
