def swift_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'

def swift_set(st):
    out = [f'    // {st["ico"]} {st["title"]}',
           '    DhikrSet(',
           f'        id: "{st["id"]}",',
           f'        title: "{st["title"]}",',
           f'        symbol: "{st["symbol"]}",',
           f'        closeTitle: "{st["closeTitle"]}",',
           f'        closeDua: "{st["closeDua"]}",',
           '        items: [']
    for i, (iid, text, target, full) in enumerate(st['items']):
        if full:
            out.append(f'            Dhikr(id: "{iid}", text: {swift_str(text)}, target: {target},')
            out.append(f'                  full: {swift_str(full)}),')
        else:
            out.append(f'            Dhikr(id: "{iid}", text: {swift_str(text)}, target: {target}, full: nil),')
    out += ['        ]', '    ),', '']
    return '\n'.join(out)


