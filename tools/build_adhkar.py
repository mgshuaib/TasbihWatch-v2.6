def js_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'

def js_set(st):
    # 🎛️ أيقونة متجهة للمحاكي تقابل رمز أبل في التطبيق (بلا إيموجي ضبابية)
    SIM_SYM = {
        'figure.mind.and.body': 'person',
        'sunrise': 'sunrise',
        'moon.stars': 'moon',
        'bed.double': 'bed',
        'sparkles': 'sparkles',
        'infinity': 'infinity',
        'arrow.triangle.2.circlepath': 'cycle',
        'heart.fill': 'heart',
    }
    out = [f'  {{ id:"{st["id"]}", ico:"{st["ico"]}", sym:"{SIM_SYM.get(st["symbol"], "dot")}", title:"{st["title"]}",',
           f'    closeTitle:"{st["closeTitle"]}",',
           f'    closeDua:"{st["closeDua"]}",',
           '    items:[']
    rows = []
    for iid, text, target, full in st['items']:
        rows.append(f'      {{id:"{iid}", t:{js_str(text)}, n:{target}}},')
    out.append('\n'.join(rows))
    out.append('    ]},')
    return '\n'.join(out)


def build_full_entries(sw):
    """كل نص كامل في التطبيق: من Swift الجديد (المصدر الوحيد)."""
    k = sw.find('let adhkarSets: [DhikrSet] = [')
    block = sw[k:sw.find('\n]\n', k)]
    label_fulls, order = {}, []
    for m in re.finditer(r'Dhikr\((.*?)\)\s*,?\s*(?=Dhikr\(|\])', block, re.S):
        body = ' '.join(m.group(1).split())
        t = re.search(r'text:\s*"((?:[^"\\]|\\.)*)"', body)
        f = re.search(r'full:\s*"((?:[^"\\]|\\.)*)"', body)
        if not (t and f):
            continue
        label, full = t.group(1), f.group(1)
        if label in label_fulls:
            if label_fulls[label] != full:
                raise SystemExit(f'✘ نصّان مختلفان لعنوان واحد: {label}')
        else:
            label_fulls[label] = full
            order.append(label)
    return [(lbl, label_fulls[lbl]) for lbl in order]


def main():
    sw_path, sim_path = ROOT / 'Shared.swift', ROOT / 'simulator.html'
    sw, sim = sw_path.read_text(encoding='utf-8'), sim_path.read_text(encoding='utf-8')

    # ── ① Swift: استبدال المجموعات الأربع الأولى ──
    k = sw.find('let adhkarSets: [DhikrSet] = [')
    tail_marker = '    DhikrSet(\n        id: "general"'
    j = sw.find(tail_marker, k)
    if k < 0 or j < 0:
        raise SystemExit('✘ لم أجد حدود مجموعات Swift')
    head, tail = sw[:k], sw[j:]
    new_sw = head + 'let adhkarSets: [DhikrSet] = [\n\n' + '\n'.join(swift_set(s) for s in BOOK) + tail

    # ── ② المحاكي: استبدال SETS الأربع ──
    k2 = sim.find('  { id:"after_prayer"')
    j2 = sim.find('  { id:"general"', k2)
